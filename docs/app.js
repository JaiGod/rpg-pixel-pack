// ------------------------------------------------------------------ input
const keys = new Set();
const pressed = new Set();
const KEYMAP = { KeyW: 'up', ArrowUp: 'up', KeyS: 'down', ArrowDown: 'down', KeyA: 'left', ArrowLeft: 'left', KeyD: 'right', ArrowRight: 'right',
  ShiftLeft: 'run', ShiftRight: 'run', Space: 'attack', KeyJ: 'attack', KeyE: 'talk', Enter: 'talk', KeyR: 'restart' };
window.addEventListener('keydown', e => {
  const k = KEYMAP[e.code];
  if (!k || !Game.active) return;
  if (!keys.has(k)) pressed.add(k);
  keys.add(k);
  e.preventDefault();
});
window.addEventListener('keyup', e => { const k = KEYMAP[e.code]; if (k) keys.delete(k); });
window.addEventListener('blur', () => keys.clear());
document.querySelectorAll('#touch button').forEach(b => {
  const k = b.dataset.k;
  const on = e => { e.preventDefault(); if (!keys.has(k)) pressed.add(k); keys.add(k); };
  const off = e => { e.preventDefault(); keys.delete(k); };
  b.addEventListener('pointerdown', on); b.addEventListener('pointerup', off); b.addEventListener('pointerleave', off); b.addEventListener('pointercancel', off);
});

// ------------------------------------------------------------------ GAME
const Game = (() => {
  const cv = document.getElementById('game');
  const ctx = cv.getContext('2d');
  ctx.imageSmoothingEnabled = false;
  const W = 44, H = 26, T = 32;
  let tiles = null, statics = [], npcs = [], mons = [], fx = [], player = null, started = false, ready = false;
  let cam = { x: 0, y: 0 }, msg = { text: '', t: 0 }, last = 0, rafId = 0;
  const G = { active: true };

  function rng(seed) { let s = seed >>> 0; return () => ((s = (s * 1664525 + 1013904223) >>> 0) / 4294967296); }

  function buildMap() {
    const C = [];
    for (let y = 0; y <= H; y++) { C.push(new Array(W + 1).fill(0)); }
    for (let x = 0; x <= W; x++) { C[12][x] = 1; C[13][x] = 1; }
    for (let y = 0; y <= H; y++) { C[y][21] = 1; C[y][22] = 1; }
    for (let y = 0; y <= H; y++) for (let x = 0; x <= W; x++) if (((x - 21.5) / 4.5) ** 2 + ((y - 12.5) / 3.2) ** 2 <= 1) C[y][x] = 1;
    const r = rng(7);
    tiles = [];
    for (let y = 0; y < H; y++) {
      const row = [];
      for (let x = 0; x < W; x++) {
        const idx = C[y][x] * 8 + C[y][x + 1] * 4 + C[y + 1][x] * 2 + C[y + 1][x + 1];
        if (idx === 0) row.push(r() < 0.12 ? [4 + Math.floor(r() * 4), 0] : [Math.floor(r() * 4), 0]);
        else if (idx === 15) row.push([Math.floor(r() * 4), 3]);
        else row.push([idx % 8, 1 + Math.floor(idx / 8)]);
      }
      tiles.push(row);
    }
  }

  const byId = (list, id) => list.find(i => i.id === id);
  async function addStatic(file, x, y, solid) {
    const img = await loadImg(file);
    statics.push({ img, x, y, w: img.width, h: img.height, solid });
  }
  async function building(id, tx, ty) {
    const b = byId(P.buildings.items, id);
    const [cx, cy, cw, ch] = b.collision_rect;
    const x = tx * T, y = ty * T;
    await addStatic(b.file, x, y, { x: x - b.size[0] / 2 + cx, y: y - b.size[1] + cy, w: cw, h: ch });
  }
  async function prop(id, x, y, solid = true) {
    const p = byId(P.environments.props, id);
    const w = p.size[0];
    await addStatic(p.file, x, y, solid ? { x: x - w * 0.15, y: y - 10, w: w * 0.3, h: 8 } : null);
  }
  async function anim(id, x, y) {
    const a = byId(P.animations.items, id);
    const img = await loadImg(a.file);
    statics.push({ img, x, y, w: a.frame_size[0], h: a.frame_size[1], anim: a, solid: null });
  }

  async function setup() {
    buildMap();
    statics = []; npcs = []; mons = []; fx = [];
    const tileset = await loadImg('environments/tilesets/village.png');
    G.tileset = tileset;
    await Promise.all([
      building('house_small_cottage', 6, 11), building('shop_general', 11, 11), building('shop_potion', 16, 11),
      building('inn_tavern', 29, 11), building('blacksmith_forge', 37, 11), building('tower_arcane', 41, 24),
      building('house_small_thatch', 6, 19), building('farm_red_barn', 13, 21),
      prop('well', 21.5 * T, 15 * T), prop('lamp_post', 19 * T, 12 * T), prop('lamp_post', 24 * T, 12 * T),
      anim('campfire', 25 * T, 15.5 * T), anim('flag_red', 26 * T, 11 * T), anim('windmill', 17 * T, 22 * T),
    ]);
    const trees = ['tree_oak', 'tree_cherry', 'tree_autumn', 'tree_big', 'tree_pine'];
    const r = rng(3);
    const jobs = [];
    for (let i = 0; i < 40; i++) {
      const px = 1 + Math.floor(r() * (W - 2)), py = 2 + Math.floor(r() * (H - 3));
      if (Math.abs(py - 12.5) < 3.5 || Math.abs(px - 21.5) < 3 || (py < 12 && px > 3 && px < 40) || (px > 3 && px < 17 && py > 15 && py < 22) || (px > 29 && py > 17)) continue;
      jobs.push(prop(trees[i % trees.length], px * T, py * T));
    }
    await Promise.all(jobs);
    // player
    const pcfg = { sex: 'male', layers: { body: ['skin_tan'], hair: ['spiky', 'hair_brown'], legs: ['boots', 'cloth_brown', 'leather'],
      torso: ['tunic', 'cloth_blue', 'cloth_yellow'], cape: ['cape', 'cloth_red', 'gold'], weapon: ['sword'], offhand: ['round_shield'] } };
    player = { x: 21 * T, y: 13.5 * T, dir: 'down', flip: false, anim: 'idle', t: 0, sheet: await composeCharacter(pcfg), hp: 10, max: 10, atk: false, hurt: 0, dead: false };
    // npcs
    const NPCS = [['merchant_trader', 'male', 'Trader Amir', ['Fresh wares from the desert!', 'Gold talks, friend.']],
      ['farmer_homesteader', 'female', 'Farmer Hilde', ['Slimes keep eating my turnips...', 'The well water is the best around.']],
      ['knight_royal_guard', 'male', 'Guard Bram', ['Stay out of the meadow after dark.', 'Press Space to swing your sword!']],
      ['mage_apprentice', 'female', 'Apprentice Lin', ['The tower door is stuck again.', 'Have you seen my wand?']],
      ['pirate_deckhand', 'male', 'Sailor Pip', ['Arr. Wrong biome, I know.']],
      ['scientist_biologist', 'female', 'Dr. Vale', ['These slimes are fascinating!', 'Try the Character Creator tab.']]];
    for (let i = 0; i < NPCS.length; i++) {
      const [pid, sex, name, lines] = NPCS[i];
      const pr = byId(P.characters.presets, pid);
      const sheet = await loadImg('characters/' + pr.files[sex]);
      const x = (8 + i * 5) * T, y = (13 + (i % 2) * 2) * T;
      npcs.push({ x, y, hx: x, hy: y, dir: 'down', flip: false, anim: 'idle', t: Math.random(), sheet, name, lines, li: 0, wait: 1 + Math.random() * 2, tx: x, ty: y, say: '', sayT: 0 });
    }
    // monsters
    const MONS = [['slime_green', 33, 20], ['slime_blue', 36, 22], ['slime_forest', 31, 23], ['slime_fire', 34, 24], ['goblin_grunt', 38, 19], ['shadow_bat', 6, 23], ['slime_poison', 3, 4]];
    for (const [id, tx, ty] of MONS) await spawnMonster(id, tx * T, ty * T);
    ready = true;
  }
  async function spawnMonster(id, x, y) {
    const m = byId(P.monsters.monsters, id);
    const img = await loadImg(m.file);
    mons.push({ id, m, img, x, y, hx: x, hy: y, size: m.frame_size[0], layout: m.layout, anim: 'idle', t: 0, flip: false, dir: 'side',
      hp: 3, state: 'wander', wait: 0, tx: x, ty: y, vx: 0, vy: 0 });
  }

  // collision
  function blocked(x, y) {
    const box = { x: x - 6, y: y - 6, w: 12, h: 6 };
    if (box.x < 4 || box.y < 36 || box.x + box.w > W * T - 4 || box.y + box.h > H * T - 4) return true;
    for (const s of statics) {
      const c = s.solid;
      if (c && box.x < c.x + c.w && box.x + box.w > c.x && box.y < c.y + c.h && box.y + box.h > c.y) return true;
    }
    return false;
  }
  function moveEnt(e, dx, dy) {
    if (!blocked(e.x + dx, e.y)) e.x += dx;
    if (!blocked(e.x, e.y + dy)) e.y += dy;
  }
  function faceVec(e, vx, vy) {
    if (Math.abs(vx) > Math.abs(vy)) { e.dir = 'side'; e.flip = vx < 0; } else if (vy !== 0) { e.dir = vy > 0 ? 'down' : 'up'; e.flip = false; }
  }
  function setAnim(e, a) { if (e.anim !== a) { e.anim = a; e.t = 0; } }
  function frameOf(e, fps, n, loop) {
    const f = Math.floor(e.t * fps);
    return loop ? f % n : Math.min(f, n - 1);
  }
  function charAnimDone(e) {
    const a = ANIM_BY_NAME[e.anim + '_' + e.dir];
    return a && e.t * a.fps >= a.frames;
  }

  function update(dt) {
    if (!ready) return;
    const p = player;
    if (pressed.has('restart')) { p.hp = p.max; p.dead = false; p.x = 21 * T; p.y = 13.5 * T; setAnim(p, 'idle'); }
    p.t += dt;
    if (p.dead) { /* stay down */ }
    else if (p.hurt > 0) { p.hurt -= dt; moveEnt(p, p.kx * dt * 120, p.ky * dt * 120); if (p.hurt <= 0) setAnim(p, 'idle'); }
    else if (p.atk) { if (charAnimDone(p)) { p.atk = false; setAnim(p, 'idle'); } }
    else {
      let vx = (keys.has('right') ? 1 : 0) - (keys.has('left') ? 1 : 0);
      let vy = (keys.has('down') ? 1 : 0) - (keys.has('up') ? 1 : 0);
      const len = Math.hypot(vx, vy) || 1;
      const run = keys.has('run');
      const sp = (run ? 125 : 70) * dt;
      if (vx || vy) { faceVec(p, vx, vy); moveEnt(p, vx / len * sp, vy / len * sp); setAnim(p, run ? 'run' : 'walk'); }
      else setAnim(p, 'idle');
      if (pressed.has('attack')) {
        p.atk = true; setAnim(p, 'attack');
        const fx_ = p.dir === 'side' ? (p.flip ? -1 : 1) : 0, fy = p.dir === 'down' ? 1 : p.dir === 'up' ? -1 : 0;
        for (const m of mons) {
          const dx = m.x - p.x, dy = m.y - p.y, d = Math.hypot(dx, dy);
          if (d < 30 && (dx * fx_ + dy * fy) / (d || 1) > 0.2 && m.state !== 'dead') hitMonster(m, fx_, fy);
        }
      }
      if (pressed.has('talk')) {
        let best = null, bd = 34;
        for (const n of npcs) { const d = Math.hypot(n.x - p.x, n.y - p.y); if (d < bd) { bd = d; best = n; } }
        if (best) {
          const line = best.lines[best.li++ % best.lines.length];
          best.say = line; best.sayT = 3; best.wait = 3; faceVec(best, p.x - best.x, p.y - best.y); setAnim(best, 'idle');
          msg = { text: best.name + ': ' + line, t: 4 };
        } else msg = { text: 'Nobody to talk to here.', t: 1.5 };
      }
    }
    for (const n of npcs) {
      n.t += dt;
      if (n.sayT > 0) n.sayT -= dt;
      if (n.wait > 0) { n.wait -= dt; setAnim(n, 'idle'); if (n.wait <= 0) { const a = Math.random() * 6.28, r = 8 + Math.random() * 44; n.tx = n.hx + Math.cos(a) * r; n.ty = n.hy + Math.sin(a) * r; } continue; }
      const dx = n.tx - n.x, dy = n.ty - n.y, d = Math.hypot(dx, dy);
      if (d < 2) { n.wait = 1 + Math.random() * 3; continue; }
      const ox = n.x, oy = n.y;
      moveEnt(n, dx / d * 28 * dt, dy / d * 28 * dt);
      if (ox === n.x && oy === n.y) n.wait = 0.6;
      faceVec(n, dx, dy); setAnim(n, 'walk');
    }
    for (const m of mons) updateMonster(m, dt);
    mons = mons.filter(m => !(m.state === 'dead' && m.t > 1.6));
    if (mons.length < 4 && Math.random() < dt * 0.2) {
      const ids = ['slime_green', 'slime_blue', 'slime_forest', 'slime_ice', 'slime_gold'];
      spawnMonster(ids[Math.floor(Math.random() * ids.length)], (30 + Math.random() * 10) * T, (19 + Math.random() * 5) * T);
    }
    for (const s of statics) if (s.anim) s.t = (s.t || 0) + dt;
    if (msg.t > 0) msg.t -= dt;
    cam.x = Math.max(0, Math.min(W * T - cv.width, p.x - cv.width / 2));
    cam.y = Math.max(0, Math.min(H * T - cv.height, p.y - cv.height / 2));
  }

  function monAnimLen(m, base) {
    if (m.layout === 'character') { const a = ANIM_BY_NAME[(base === 'move' ? 'walk' : base) + '_' + m.dir]; return a; }
    return MON_LAYOUT.creature.animations.find(a => a.name === base);
  }
  function hitMonster(m, fx_, fy) {
    m.hp -= 1; m.flash = 0.1;
    if (m.hp <= 0) { m.state = 'dead'; m.anim = 'death'; m.t = 0; msg = { text: 'Defeated ' + m.m.name + '!', t: 2 }; return; }
    m.state = 'hurt'; m.anim = 'hurt'; m.t = 0; m.vx = fx_ * 110; m.vy = fy * 110;
  }
  function updateMonster(m, dt) {
    m.t += dt; if (m.flash > 0) m.flash -= dt;
    const p = player;
    const a = monAnimLen(m, m.anim);
    const done = a && m.t * a.fps >= a.frames;
    if (m.state === 'dead') return;
    if (m.state === 'hurt') { moveEnt(m, m.vx * dt, m.vy * dt); m.vx *= 0.85; m.vy *= 0.85; if (done) { m.state = 'wander'; m.anim = 'idle'; } return; }
    if (m.state === 'attack') {
      if (done) {
        if (!p.dead && Math.hypot(p.x - m.x, p.y - m.y) < 26 && p.hurt <= 0) {
          p.hp -= 1; p.hurt = 0.3; const d = Math.hypot(p.x - m.x, p.y - m.y) || 1; p.kx = (p.x - m.x) / d; p.ky = (p.y - m.y) / d; p.atk = false;
          if (p.hp <= 0) { p.dead = true; setAnim(p, 'death'); msg = { text: 'You were defeated — press R to restart', t: 99 }; } else setAnim(p, 'hurt');
        }
        m.state = 'wander'; m.anim = 'idle'; m.t = 0; m.wait = 0.5;
      }
      return;
    }
    const dx = p.x - m.x, dy = p.y - m.y, d = Math.hypot(dx, dy);
    const setA = n => { if (m.anim !== n) { m.anim = n; m.t = 0; } };
    const face = (vx, vy) => { if (m.layout === 'character') faceVec(m, vx, vy); else if (Math.abs(vx) > 0.01) m.flip = vx < 0; };
    if (!p.dead && d < 18) { face(dx, dy); m.state = 'attack'; setA('attack'); m.t = 0; return; }
    if (!p.dead && d < 90) { face(dx, dy); moveEnt(m, dx / d * 42 * dt, dy / d * 42 * dt); setA('move'); return; }
    m.wait -= dt;
    if (m.wait <= 0) { m.wait = 1 + Math.random() * 2; const an = Math.random() * 6.28; m.tx = m.hx + Math.cos(an) * 40 * Math.random(); m.ty = m.hy + Math.sin(an) * 40 * Math.random(); }
    const tx = m.tx - m.x, ty = m.ty - m.y, td = Math.hypot(tx, ty);
    if (td > 3) { face(tx, ty); moveEnt(m, tx / td * 30 * dt, ty / td * 30 * dt); setA('move'); } else setA('idle');
  }

  function draw() {
    ctx.fillStyle = '#000'; ctx.fillRect(0, 0, cv.width, cv.height);
    if (!ready) { ctx.fillStyle = '#ece8f4'; ctx.font = '12px monospace'; ctx.fillText('Loading pack…', 270, 180); return; }
    const cx = Math.round(cam.x), cy = Math.round(cam.y);
    const x0 = Math.floor(cx / T), y0 = Math.floor(cy / T);
    for (let y = y0; y <= y0 + Math.ceil(cv.height / T) && y < H; y++)
      for (let x = x0; x <= x0 + Math.ceil(cv.width / T) && x < W; x++) {
        const [tc, tr] = tiles[y][x];
        ctx.drawImage(G.tileset, tc * T, tr * T, T, T, x * T - cx, y * T - cy, T, T);
      }
    const list = [];
    for (const s of statics) list.push({ y: s.y, f: () => {
      if (s.anim) { const n = s.anim.frames, fi = Math.floor(s.t * s.anim.fps) % n; ctx.drawImage(s.img, fi * s.w, 0, s.w, s.h, Math.round(s.x - s.w / 2 - cx), Math.round(s.y - s.h - cy), s.w, s.h); }
      else ctx.drawImage(s.img, Math.round(s.x - s.w / 2 - cx), Math.round(s.y - s.h - cy));
    } });
    const charDraw = (e) => () => {
      const a = ANIM_BY_NAME[e.anim + '_' + e.dir];
      drawCharFrame(ctx, e.sheet, e.anim + '_' + e.dir, frameOf(e, a.fps, a.frames, a.loop), e.x - cx, e.y - cy, e.flip);
    };
    list.push({ y: player.y, f: () => { if (player.hurt > 0 && Math.floor(player.hurt * 20) % 2) ctx.globalAlpha = 0.5; charDraw(player)(); ctx.globalAlpha = 1; } });
    for (const n of npcs) list.push({ y: n.y, f: charDraw(n) });
    for (const m of mons) list.push({ y: m.y, f: () => {
      const s = m.size;
      let row, fi;
      if (m.layout === 'character') {
        const a = ANIM_BY_NAME[(m.anim === 'move' ? 'walk' : m.anim) + '_' + m.dir];
        row = a.row; fi = frameOf(m, a.fps, a.frames, a.loop);
      } else {
        const ai = MON_LAYOUT.creature.animations.findIndex(a => a.name === m.anim);
        const a = MON_LAYOUT.creature.animations[ai];
        row = ai; fi = frameOf(m, a.fps, a.frames, a.loop);
      }
      ctx.save();
      ctx.translate(Math.round(m.x - cx), Math.round(m.y - cy));
      if (m.flip) ctx.scale(-1, 1);
      if (m.state === 'dead') ctx.globalAlpha = Math.max(0, 1 - Math.max(0, m.t - 0.8) / 0.8);
      if (m.flash > 0) ctx.filter = 'brightness(3)';
      ctx.drawImage(m.img, fi * s, row * s, s, s, -s / 2, m.layout === 'character' ? -30 : -s + 2, s, s);
      ctx.restore();
    } });
    list.sort((a, b) => a.y - b.y).forEach(o => o.f());
    // speech bubbles
    ctx.font = '8px monospace'; ctx.textAlign = 'center';
    for (const n of npcs) if (n.sayT > 0) bubble(n.say, n.x - cx, n.y - cy - 40);
    for (const n of npcs) if (Math.hypot(n.x - player.x, n.y - player.y) < 34 && n.sayT <= 0) bubble('E', n.x - cx, n.y - cy - 38);
    // HUD
    ctx.textAlign = 'left';
    ctx.fillStyle = 'rgba(20,16,30,.75)'; ctx.fillRect(6, 6, 106, 14);
    ctx.fillStyle = '#5a3422'; ctx.fillRect(9, 9, 100, 8);
    ctx.fillStyle = '#d23a40'; ctx.fillRect(9, 9, 100 * Math.max(0, player.hp) / player.max, 8);
    ctx.fillStyle = '#fff'; ctx.font = '8px monospace'; ctx.fillText('HP ' + Math.max(0, player.hp) + '/' + player.max, 12, 16);
    if (msg.t > 0) { ctx.fillStyle = 'rgba(20,16,30,.8)'; const w = ctx.measureText(msg.text).width + 12; ctx.fillRect(6, cv.height - 20, w, 14); ctx.fillStyle = '#f7e08a'; ctx.fillText(msg.text, 12, cv.height - 10); }
  }
  function bubble(text, x, y) {
    const w = Math.min(ctx.measureText(text).width + 8, 220);
    ctx.fillStyle = 'rgba(244,241,234,.95)'; ctx.fillRect(Math.round(x - w / 2), Math.round(y - 9), Math.round(w), 12);
    ctx.fillStyle = '#2a2135'; ctx.fillText(text, Math.round(x), Math.round(y));
  }
  function loop(ts) {
    const dt = Math.min(0.05, (ts - last) / 1000 || 0);
    last = ts;
    if (G.active && started) update(dt);
    pressed.clear();
    draw();
    rafId = requestAnimationFrame(loop);
  }
  G.start = async () => {
    if (!started) { started = true; document.getElementById('gameStart').style.display = 'none'; document.body.classList.add('playing'); }
    cv.focus();
  };
  G.setActive = v => { G.active = v; if (!v) keys.clear(); };
  G.boot = async () => { await setup(); requestAnimationFrame(loop); };
  return G;
})();
