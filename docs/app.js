// ------------------------------------------------------------------ assets
const imgCache = new Map();
function loadImg(path) {
  if (!imgCache.has(path)) {
    imgCache.set(path, new Promise((res, rej) => {
      const i = new Image();
      i.onload = () => res(i);
      i.onerror = () => rej(new Error('missing ' + path));
      i.src = BASE + path;
    }));
  }
  return imgCache.get(path);
}
const hex = h => [parseInt(h.slice(1, 3), 16), parseInt(h.slice(3, 5), 16), parseInt(h.slice(5, 7), 16)];
function rampRGB(name) { return (P.ramps[name] || []).map(hex); }

const recolorCache = new Map();
async function layerImage(path, primary, secondary) {
  const key = path + '|' + (primary || '') + '|' + (secondary || '');
  if (recolorCache.has(key)) return recolorCache.get(key);
  const pr = (async () => {
    const img = await loadImg(path);
    if (!primary && !secondary) return img;
    const c = document.createElement('canvas');
    c.width = img.width; c.height = img.height;
    const x = c.getContext('2d');
    x.drawImage(img, 0, 0);
    const d = x.getImageData(0, 0, c.width, c.height);
    const map = new Map();
    const add = (keys, ramp) => { if (ramp && ramp.length === 4) keys.forEach((k, i) => map.set(k.join(','), ramp[i])); };
    add(KEYS.primary, rampRGB(primary));
    add(KEYS.secondary, rampRGB(secondary));
    const a = d.data;
    for (let i = 0; i < a.length; i += 4) {
      if (!a[i + 3]) continue;
      const m = map.get(a[i] + ',' + a[i + 1] + ',' + a[i + 2]);
      if (m) { a[i] = m[0]; a[i + 1] = m[1]; a[i + 2] = m[2]; }
    }
    x.putImageData(d, 0, 0);
    return c;
  })();
  recolorCache.set(key, pr);
  return pr;
}

const LAYER_ORDER = P.characters.layer_order;
const HIDE_HAIR = ['knight_helm', 'space_helmet', 'hood', 'necro_cowl'];
/** cfg: {sex, layers: {kind: [style, primary, secondary]}} -> 192x576 canvas */
async function composeCharacter(cfg) {
  const c = document.createElement('canvas');
  c.width = 192; c.height = 576;
  const x = c.getContext('2d');
  const head = cfg.layers.head && cfg.layers.head[0];
  for (const kind of LAYER_ORDER) {
    const l = cfg.layers[kind];
    if (!l || !l[0]) continue;
    if ((kind === 'hair' || kind === 'hair_back') && HIDE_HAIR.includes(head)) continue;
    if (kind === 'hair_back' && !P.characters.layers.hair_back.styles.includes(l[0])) continue;
    try {
      const im = await layerImage(`characters/layers/${cfg.sex}/${kind}/${l[0]}.png`, l[1], l[2]);
      x.drawImage(im, 0, 0);
    } catch (e) { /* missing layer: skip */ }
  }
  return c;
}
function presetConfig(preset, sex) {
  const layers = {};
  for (const r of preset.layer_recipe[sex]) layers[r.layer] = [r.style, r.primary, r.secondary];
  return { sex, layers };
}

// draw one 32x32 character frame (feet at x,y)
function drawCharFrame(ctx, sheet, animName, frame, x, y, flip, scale = 1) {
  const a = ANIM_BY_NAME[animName];
  if (!a || !sheet) return;
  const f = Math.min(frame, a.frames - 1);
  ctx.save();
  ctx.translate(Math.round(x), Math.round(y));
  if (flip) ctx.scale(-1, 1);
  ctx.drawImage(sheet, f * 32, a.row * 32, 32, 32, -16 * scale, -30 * scale, 32 * scale, 32 * scale);
  ctx.restore();
}

